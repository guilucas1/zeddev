#!/usr/bin/env bash
#
# Start or stop the local SMTP server the mail integration tests run against.
#
# Why a real server rather than a fake, for the third time in this repo: the
# behaviour under test is an SMTP *conversation* — greeting, EHLO capability
# negotiation, AUTH, the DATA sub-protocol with its dot-stuffing rule, and the
# exact bytes of a MIME message. A hand-written fake SMTP server would have to
# implement the same reading of RFC 5321/5322 that `src/lib/mail/smtp.ts` does in
# order to accept what it sends, and would then only prove that this repo's
# understanding of the protocol agrees with itself. A message our encoder gets
# wrong is garbled in a real mailbox and pristine in a fake built from the same
# misunderstanding. Same reasoning as `scripts/db.sh` and `scripts/storage.sh`,
# and IMPLEMENTATION_PLAN.md §4c records what it cost to learn it the other way.
#
# Mailpit specifically because it is a single ~20 MB static binary that speaks
# real SMTP and exposes every received message over an HTTP API, so a test can
# assert on what actually arrived rather than on what we believe we sent. That
# read-back is the whole point: it is the external oracle for the encoder, the
# same role the published SigV4 worked example plays in `@zeddev/storage`.
#
# Why a script rather than a line in AGENTS.md: `environment-portability.md`
# forbids "manual, undocumented, or tribal-knowledge steps".
#
# `up` writes the ZEDDEV_TEST_MAIL_* block into `.env.test`, which `npm test`
# loads via `--env-file-if-exists`. It *upserts* that block rather than rewriting
# the file, so it, `scripts/db.sh`, and `scripts/storage.sh` can be run in any
# order — a script that truncated the file would silently disable the others'
# suites depending on which ran last.
#
# The container is disposable and holds nothing worth keeping. Tests never clear
# it: test files run in parallel against this one server, so each fixture owns a
# unique recipient domain and reads only its own mail. A "clear the mailbox" step
# would delete another file's message between its send and its assertion.
set -euo pipefail

CONTAINER=zeddev-mailpit
IMAGE=axllent/mailpit:latest
SMTP_PORT="${ZEDDEV_TEST_MAIL_PORT:-51025}"
API_PORT="${ZEDDEV_TEST_MAIL_API_PORT:-58025}"
USERNAME=zeddevtest

# Not a secret. This server is created empty by this script, accepts any
# credential, holds only throwaway fixtures, and is published on the loopback
# interface only. A real deployment supplies MAIL_PASSWORD as configuration, per
# `credential-and-secret-handling.md`.
PASSWORD=zeddev_test_pw

ENV_FILE=.env.test

# Replace this script's own block in .env.test, leaving any other tool's alone.
upsert_env() {
  local tmp
  tmp="$(mktemp)"
  if [ -f "${ENV_FILE}" ]; then
    grep -v '^ZEDDEV_TEST_MAIL_' "${ENV_FILE}" > "${tmp}" || true
  else
    echo '# Generated by scripts/. Gitignored. Loaded automatically by `npm test`.' > "${tmp}"
  fi
  cat >> "${tmp}" <<ENVFILE
ZEDDEV_TEST_MAIL_HOST=127.0.0.1
ZEDDEV_TEST_MAIL_PORT=${SMTP_PORT}
ZEDDEV_TEST_MAIL_API_PORT=${API_PORT}
ZEDDEV_TEST_MAIL_USERNAME=${USERNAME}
ZEDDEV_TEST_MAIL_PASSWORD=${PASSWORD}
ENVFILE
  mv "${tmp}" "${ENV_FILE}"
}

case "${1:-up}" in
  up)
    if [ -z "$(docker ps -q -f name="^${CONTAINER}$")" ]; then
      docker rm -f "${CONTAINER}" >/dev/null 2>&1 || true
      # MP_SMTP_AUTH_ACCEPT_ANY plus MP_SMTP_AUTH_ALLOW_INSECURE make the server
      # accept AUTH over a cleartext connection. That combination is exactly what
      # a production deployment must never do, and it is set here on purpose: it
      # is what lets the suite exercise the AUTH PLAIN and AUTH LOGIN paths
      # without also standing up a certificate authority. The rule that the
      # client *refuses* to do this unless MAIL_ALLOW_INSECURE_AUTH is set is
      # covered by its own test against the connector seam.
      docker run -d --name "${CONTAINER}" \
        -e MP_SMTP_AUTH_ACCEPT_ANY=true \
        -e MP_SMTP_AUTH_ALLOW_INSECURE=true \
        -p "127.0.0.1:${SMTP_PORT}:1025" \
        -p "127.0.0.1:${API_PORT}:8025" \
        "${IMAGE}" >/dev/null
      printf 'waiting for smtp'
      for _ in $(seq 1 60); do
        if curl -fsS -o /dev/null "http://127.0.0.1:${API_PORT}/api/v1/info" 2>/dev/null; then break; fi
        printf '.'
        sleep 1
      done
      echo
    fi

    upsert_env

    cat <<MESSAGE
SMTP is running on 127.0.0.1:${SMTP_PORT} (container ${CONTAINER}).
Received mail is readable at http://127.0.0.1:${API_PORT}/ and over its API.
Updated .env.test — \`npm run check\` will now pick it up automatically.
MESSAGE
    ;;
  down)
    docker rm -f "${CONTAINER}" >/dev/null 2>&1 || true
    if [ -f "${ENV_FILE}" ]; then
      tmp="$(mktemp)"
      grep -v '^ZEDDEV_TEST_MAIL_' "${ENV_FILE}" > "${tmp}" || true
      mv "${tmp}" "${ENV_FILE}"
    fi
    echo "Removed ${CONTAINER} and its .env.test entries."
    ;;
  *)
    echo "usage: $0 [up|down]" >&2
    exit 64
    ;;
esac
