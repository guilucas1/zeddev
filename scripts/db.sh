#!/usr/bin/env bash
#
# Start or stop the local PostgreSQL the integration tests run against.
#
# Why a script rather than a line in AGENTS.md: `environment-portability.md`
# forbids "manual, undocumented, or tribal-knowledge steps", and a database that
# has to be started by hand with remembered flags is exactly that. It is also the
# thing most likely to be set up slightly differently by each person — and one of
# those differences, connecting as a superuser, silently disables every
# row-level security policy in the schema. See `src/lib/db/preflight.ts`.
#
# `up` writes the ZEDDEV_TEST_DATABASE_* block into `.env.test`, which `npm test`
# loads via `--env-file-if-exists`, so there is no export step to remember and no
# way for the isolation tests to be skipped because someone forgot one. It
# *upserts* that block rather than rewriting the file, so this and
# `scripts/storage.sh` can be run in either order — a script that truncated the
# file would silently disable the other's suite depending on which ran last.
#
# The container is disposable. Each test creates and drops its own database and
# its own unprivileged role inside it, so nothing here holds state worth keeping.
set -euo pipefail

CONTAINER=zeddev-pg
IMAGE=postgres:17-alpine
PORT="${ZEDDEV_TEST_DATABASE_PORT:-55432}"

# Not a secret. This database is created empty by this script, holds only
# throwaway fixtures, and is published on the loopback interface only. A real
# deployment supplies DATABASE_PASSWORD as configuration, per
# `credential-and-secret-handling.md`.
PASSWORD=zeddev_test_pw

ENV_FILE=.env.test

# Replace this script's own block in .env.test, leaving any other tool's alone.
upsert_env() {
  local tmp
  tmp="$(mktemp)"
  if [ -f "${ENV_FILE}" ]; then
    grep -v '^ZEDDEV_TEST_DATABASE_' "${ENV_FILE}" > "${tmp}" || true
  else
    echo '# Generated by scripts/. Gitignored. Loaded automatically by `npm test`.' > "${tmp}"
  fi
  cat >> "${tmp}" <<ENVFILE
ZEDDEV_TEST_DATABASE_HOST=127.0.0.1
ZEDDEV_TEST_DATABASE_PORT=${PORT}
ZEDDEV_TEST_DATABASE_USER=zeddev
ZEDDEV_TEST_DATABASE_PASSWORD=${PASSWORD}
ZEDDEV_TEST_DATABASE_NAME=zeddev
ENVFILE
  mv "${tmp}" "${ENV_FILE}"
}

case "${1:-up}" in
  up)
    if [ -z "$(docker ps -q -f name="^${CONTAINER}$")" ]; then
      docker rm -f "${CONTAINER}" >/dev/null 2>&1 || true
      docker run -d --name "${CONTAINER}" \
        -e POSTGRES_USER=zeddev \
        -e POSTGRES_PASSWORD="${PASSWORD}" \
        -e POSTGRES_DB=zeddev \
        -p "127.0.0.1:${PORT}:5432" \
        "${IMAGE}" >/dev/null
      printf 'waiting for postgres'
      for _ in $(seq 1 60); do
        if docker exec "${CONTAINER}" pg_isready -U zeddev -q 2>/dev/null; then break; fi
        printf '.'
        sleep 1
      done
      echo
    fi

    upsert_env

    cat <<MESSAGE
PostgreSQL is running on 127.0.0.1:${PORT} (container ${CONTAINER}).
Updated .env.test — \`npm run check\` will now pick it up automatically.

Note: the zeddev role above is a superuser and is used only to create and drop
fixtures. Every test fixture creates its own NOSUPERUSER NOBYPASSRLS role and
connects as that, because a superuser is exempt from row-level security and would
make the isolation tests pass without enforcing anything.
MESSAGE
    ;;
  down)
    docker rm -f "${CONTAINER}" >/dev/null 2>&1 || true
    if [ -f "${ENV_FILE}" ]; then
      tmp="$(mktemp)"
      grep -v '^ZEDDEV_TEST_DATABASE_' "${ENV_FILE}" > "${tmp}" || true
      mv "${tmp}" "${ENV_FILE}"
    fi
    echo "Removed ${CONTAINER} and its .env.test entries."
    ;;
  *)
    echo "usage: $0 [up|down]" >&2
    exit 64
    ;;
esac
