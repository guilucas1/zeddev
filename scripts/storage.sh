#!/usr/bin/env bash
#
# Start or stop the local S3-compatible object storage the integration tests run
# against.
#
# Why a real server rather than a fake: the behavior under test is the remote's.
# A hand-written fake S3 would have to implement SigV4 verification in order to
# test SigV4 signing, and would then only prove that this repo's understanding of
# the algorithm agrees with itself. A wrong signature against a real server is a
# 403; against a fake built from the same misunderstanding it is a 200. Same
# reasoning as `scripts/db.sh`, and IMPLEMENTATION_PLAN.md §4c records what it
# cost to learn it the other way round.
#
# Why a script rather than a line in AGENTS.md: `environment-portability.md`
# forbids "manual, undocumented, or tribal-knowledge steps".
#
# `up` writes the ZEDDEV_TEST_STORAGE_* block into `.env.test`, which `npm test`
# loads via `--env-file-if-exists`. It *upserts* that block rather than
# rewriting the file, so it and `scripts/db.sh` can be run in either order.
#
# The container is disposable. Each test creates and drops its own bucket, so
# nothing here holds state worth keeping.
set -euo pipefail

CONTAINER=zeddev-minio
IMAGE=minio/minio:latest
PORT="${ZEDDEV_TEST_STORAGE_PORT:-59000}"
ACCESS_KEY=zeddevtest

# Not a secret. This server is created empty by this script, holds only throwaway
# fixtures, and is published on the loopback interface only. A real deployment
# supplies STORAGE_SECRET_ACCESS_KEY as configuration, per
# `credential-and-secret-handling.md`.
SECRET_KEY=zeddev_test_pw

ENV_FILE=.env.test

# Replace this script's own block in .env.test, leaving any other tool's alone.
upsert_env() {
  local tmp
  tmp="$(mktemp)"
  if [ -f "${ENV_FILE}" ]; then
    grep -v '^ZEDDEV_TEST_STORAGE_' "${ENV_FILE}" > "${tmp}" || true
  else
    echo '# Generated by scripts/. Gitignored. Loaded automatically by `npm test`.' > "${tmp}"
  fi
  cat >> "${tmp}" <<ENVFILE
ZEDDEV_TEST_STORAGE_HOST=127.0.0.1
ZEDDEV_TEST_STORAGE_PORT=${PORT}
ZEDDEV_TEST_STORAGE_TLS=false
ZEDDEV_TEST_STORAGE_REGION=us-east-1
ZEDDEV_TEST_STORAGE_ACCESS_KEY_ID=${ACCESS_KEY}
ZEDDEV_TEST_STORAGE_SECRET_ACCESS_KEY=${SECRET_KEY}
ENVFILE
  mv "${tmp}" "${ENV_FILE}"
}

case "${1:-up}" in
  up)
    if [ -z "$(docker ps -q -f name="^${CONTAINER}$")" ]; then
      docker rm -f "${CONTAINER}" >/dev/null 2>&1 || true
      docker run -d --name "${CONTAINER}" \
        -e MINIO_ROOT_USER="${ACCESS_KEY}" \
        -e MINIO_ROOT_PASSWORD="${SECRET_KEY}" \
        -p "127.0.0.1:${PORT}:9000" \
        "${IMAGE}" server /data >/dev/null
      printf 'waiting for object storage'
      for _ in $(seq 1 60); do
        if curl -fsS -o /dev/null "http://127.0.0.1:${PORT}/minio/health/live" 2>/dev/null; then break; fi
        printf '.'
        sleep 1
      done
      echo
    fi

    upsert_env

    cat <<MESSAGE
Object storage is running on 127.0.0.1:${PORT} (container ${CONTAINER}).
Updated .env.test — \`npm run check\` will now pick it up automatically.
MESSAGE
    ;;
  down)
    docker rm -f "${CONTAINER}" >/dev/null 2>&1 || true
    if [ -f "${ENV_FILE}" ]; then
      tmp="$(mktemp)"
      grep -v '^ZEDDEV_TEST_STORAGE_' "${ENV_FILE}" > "${tmp}" || true
      mv "${tmp}" "${ENV_FILE}"
    fi
    echo "Removed ${CONTAINER} and its .env.test entries."
    ;;
  *)
    echo "usage: $0 [up|down]" >&2
    exit 64
    ;;
esac
